/**
 * دالة تطبيع وتوحيد النصوص العربية للبحث البيطري الذكي
 * تدمج الهمزات، تزيل التشكيل والزوائد، وتوحد الحروف لتوافق كتابة الأطباء والصيادلة
 */
function normalizeArabic(text) {
  if (!text || typeof text !== "string") return "";
  return text
    .trim()
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, "") // إزالة التشكيل والتنوين
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ـ/g, "") // إزالة التطويل
    .replace(/[%\-_\/\\.,+()]/g, " ") // استبدال الرموز بمسافات
    .replace(/\s+/g, " ")
    .trim();
}

